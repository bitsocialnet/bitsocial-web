#!/usr/bin/env node

// Samples Natural Earth's 1:110m land polygons (via world-atlas) onto an equirectangular grid and
// writes src/lib/world-dots.ts, the dot-matrix basemap behind the peer map. Run it only when the
// grid settings change: `yarn workspace @bitsocial/stats-web generate:world-dots`.

import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { geoContains } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const land = feature(require("world-atlas/land-110m.json"), "land");
const outputPath = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "lib",
  "world-dots.ts",
);

const CELL_DEGREES = 2.5;
// Antarctica and the far Arctic carry no peers and would only flatten the map.
const NORTH = 80;
const SOUTH = -57.5;
const columns = 360 / CELL_DEGREES;
const rows = (NORTH - SOUTH) / CELL_DEGREES;

const hexRows = [];
for (let row = 0; row < rows; row += 1) {
  const latitude = NORTH - (row + 0.5) * CELL_DEGREES;
  let bits = "";
  for (let column = 0; column < columns; column += 1) {
    const longitude = -180 + (column + 0.5) * CELL_DEGREES;
    bits += geoContains(land, [longitude, latitude]) ? "1" : "0";
  }
  let hex = "";
  for (let index = 0; index < bits.length; index += 4) {
    hex += Number.parseInt(bits.slice(index, index + 4), 2).toString(16);
  }
  hexRows.push(hex);
}

const source = `// Generated by scripts/generate-world-dots.mjs from Natural Earth 1:110m land (world-atlas).
// Each row is a hex bitmask of land cells, west to east, starting at the northern edge.

export const WORLD_DOTS = {
  cellDegrees: ${CELL_DEGREES},
  north: ${NORTH},
  south: ${SOUTH},
  columns: ${columns},
  rows: [
${hexRows.map((hex) => `    "${hex}",`).join("\n")}
  ],
};
`;

fs.writeFileSync(outputPath, source);
console.log(`Wrote ${path.relative(process.cwd(), outputPath)} (${columns}x${rows} cells)`);
